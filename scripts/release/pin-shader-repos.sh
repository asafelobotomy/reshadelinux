#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-2.0-or-later
# purpose:  Pin every shader pack in the built-in registry to a commit, recorded in
#           lib/shader_pins.sh. Installs check out the pinned commit instead of whatever the
#           default branch holds that day, so a change upstream reaches users only after review.
# when:     Before a release, or after adding a pack to SHADER_REPOS in lib/config.sh.
# inputs:   Optional local names (such as sweetfx-shaders) to re-pin; the others keep their
#           commit. With no names every pack is re-pinned. --check reports what moved upstream
#           and writes nothing.
# outputs:  Rewrites lib/shader_pins.sh and prints one line per pack whose commit changed, with a
#           GitHub compare link to review before committing.
# risk:     network (git ls-remote only, nothing is cloned)
# source:   original
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
pins_file="$root/lib/shader_pins.sh"

# shellcheck source=../../lib/logging.sh
source "$root/lib/logging.sh"
# shellcheck source=../../lib/ui.sh
source "$root/lib/ui.sh"
# shellcheck source=../../lib/config.sh
source "$root/lib/config.sh"
# shellcheck source=../../lib/state.sh
source "$root/lib/state.sh"
# shellcheck source=../../lib/shader_registry.sh
source "$root/lib/shader_registry.sh"
# shellcheck source=../../lib/integrity.sh
source "$root/lib/integrity.sh"
# shellcheck source=../../lib/shader_pins.sh
[[ -f $pins_file ]] && source "$pins_file"

check_only=0
declare -A wanted=()
for arg in "$@"; do
    case $arg in
        --check) check_only=1 ;;
        -*) printf 'Unknown option: %s\n' "$arg" >&2; exit 2 ;;
        *) wanted["$arg"]=1 ;;
    esac
done

unset SHADER_REPOS
MAIN_PATH="$(mktemp -d)"
trap 'rm -rf "$MAIN_PATH"' EXIT
UI_BACKEND=cli init_runtime_config >/dev/null

declare -a lines=()
changed=0 failed=0
while IFS= read -r entry || [[ -n $entry ]]; do
    parseShaderRepoEntry "$entry"
    # shellcheck disable=SC2154  # set by parseShaderRepoEntry
    uri="$_shaderRepoUri" branch="$_shaderRepoBranch" name="$_shaderRepoName"
    old=$(shaderRepoPinnedCommit "$uri" "$branch") || old=""
    new="$old"
    if [[ ${#wanted[@]} -eq 0 || -n ${wanted[$name]:-} || -z $old ]]; then
        ref="HEAD"
        [[ -n $branch ]] && ref="refs/heads/$branch"
        if ! new=$(GIT_TERMINAL_PROMPT=0 git ls-remote "$uri" "$ref" | awk 'NR == 1 { print $1 }') || [[ -z $new ]]; then
            printf 'FAILED  %-28s %s (keeping %s)\n' "$name" "$uri" "${old:-no pin}" >&2
            failed=$((failed + 1))
            new="$old"
        fi
    fi
    if [[ $new != "$old" ]]; then
        changed=$((changed + 1))
        if [[ -n $old ]]; then
            printf 'MOVED   %-28s %s/compare/%s...%s\n' "$name" "${uri%.git}" "${old:0:12}" "${new:0:12}"
        else
            printf 'NEW     %-28s %s/commit/%s\n' "$name" "${uri%.git}" "$new"
        fi
    fi
    [[ -n $new ]] && lines+=("$uri ${branch:--} $new")
done < <(listConfiguredShaderRepoEntries)

printf '%d pack(s) changed, %d could not be checked.\n' "$changed" "$failed"
[[ $check_only -eq 1 ]] && exit 0

{
    printf '# shellcheck shell=bash\n'
    printf '# SPDX-License-Identifier: GPL-2.0-or-later\n'
    printf '# The commit each built-in shader pack is installed at: URL, branch ("-" for the default\n'
    printf '# branch) and commit. Generated by scripts/release/pin-shader-repos.sh; do not edit by hand.\n\n'
    printf 'function listPinnedShaderRepos() {\n'
    printf "    cat <<'EOF'\n"
    printf '%s\n' "${lines[@]}"
    printf 'EOF\n}\n'
} > "$pins_file.tmp"
mv "$pins_file.tmp" "$pins_file"
printf 'Wrote %s\n' "${pins_file#"$root"/}"
