#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-2.0-or-later
# purpose:  Record the SHA-256 of official ReShade setup executables in lib/reshade_pins.sh, the
#           only builds the installer downloads without RESHADE_SETUP_SHA256 or
#           RESHADE_ALLOW_UNPINNED=1.
# when:     A new ReShade release is out. Review the result, then commit it with the release.
# inputs:   Versions to pin, such as 6.8.0 (each is pinned with and without add-on support).
#           With no arguments, the version reshade.me currently offers.
# outputs:  Rewrites lib/reshade_pins.sh, keeping earlier pins, newest version first.
# risk:     downloads the setup executables into a temporary directory; never runs them.
# source:   original
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
pins_file="$root/lib/reshade_pins.sh"
base_url="https://reshade.me/downloads"

function fail() {
    printf 'Error: %s\n' "$*" >&2
    exit 1
}

function latest_version() {
    local html
    html=$(curl --fail --max-time 20 -sL https://reshade.me) || fail "Could not reach reshade.me."
    grep -oE '/downloads/ReShade_Setup_[0-9][0-9.]*[0-9]\.exe' <<< "$html" | head -n1 \
        | sed -E 's|.*ReShade_Setup_([0-9.]+)\.exe|\1|'
}

# Print the version and digest of every pin already in the file.
function existing_pins() {
    [[ -f $pins_file ]] || return 0
    sed -nE 's/^([0-9][0-9.]*(_Addon)?) ([0-9a-f]{64})$/\1 \3/p' "$pins_file"
}

function hash_setup() {
    local name="$1" dir="$2" digest _
    curl --fail --max-time 120 -sSL -o "$dir/$name.exe" "$base_url/ReShade_Setup_$name.exe" \
        || fail "Could not download ReShade_Setup_$name.exe."
    file "$dir/$name.exe" | grep -q 'PE32 executable' || fail "ReShade_Setup_$name.exe is not a Windows executable."
    read -r digest _ < <(sha256sum "$dir/$name.exe")
    printf '%s %s\n' "$name" "$digest"
}

command -v curl >/dev/null || fail "curl is required."
command -v file >/dev/null || fail "file is required."

versions=("$@")
if [[ ${#versions[@]} -eq 0 ]]; then
    versions=("$(latest_version)")
    [[ -n ${versions[0]} ]] || fail "Could not find the current version on reshade.me."
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

declare -A pins=()
while read -r name digest; do
    pins["$name"]="$digest"
done < <(existing_pins)

for version in "${versions[@]}"; do
    [[ $version =~ ^[0-9]+(\.[0-9]+)+$ ]] || fail "Not a ReShade version: $version"
    for name in "$version" "${version}_Addon"; do
        read -r name digest < <(hash_setup "$name" "$tmp")
        if [[ -n ${pins[$name]:-} && ${pins[$name]} != "$digest" ]]; then
            fail "ReShade_Setup_$name.exe changed since it was pinned (${pins[$name]} -> $digest). Find out why before re-pinning."
        fi
        pins["$name"]="$digest"
        printf 'Pinned %s %s\n' "$name" "$digest"
    done
done

{
    printf '# shellcheck shell=bash\n'
    printf '# SPDX-License-Identifier: GPL-2.0-or-later\n'
    printf '# SHA-256 of the official ReShade setup executables the installer accepts, newest first.\n'
    printf '# Generated by scripts/release/pin-reshade.sh; do not edit by hand.\n\n'
    printf 'function listPinnedReshadeSetups() {\n'
    printf "    cat <<'EOF'\n"
    for name in "${!pins[@]}"; do
        printf '%s %s\n' "$name" "${pins[$name]}"
    done | sort -t ' ' -k1,1Vr
    printf 'EOF\n}\n'
} > "$pins_file.tmp"
mv "$pins_file.tmp" "$pins_file"
printf 'Wrote %s\n' "${pins_file#"$root"/}"
